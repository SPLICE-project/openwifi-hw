#!/usr/bin/env bash
#
# Usage:
#   ./gen_rx_vector.sh <H_size> <NAME_FINAL_IQ>
# generates simualted transmission with hole bheavior.
# Mostly written by Claude Code
#
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"

# ------------------------------------------------------------- hardcoded config
PRE=100     # zero samples prepended before the frame
POST=200    # zero samples appended after the frame
FC_MHZ=5220 # Fc_in_MHz written into the RX metadata header

usage() {
  cat >&2 <<EOF
usage: $0 <H_size> <NAME_FINAL_IQ>

  H_size         hole size in samples, 0..160 (0 = baseline)
  NAME_FINAL_IQ  output name for the padded vector the RX reads
                 (bare name -> out/<name>)

example: $0 56 tx_H56.txt
EOF
  exit 1
}

die() {
  echo "error: $*" >&2
  exit 1
}

# ------------------------------------------------------------------- arguments
(($# == 2)) || usage

H="$1"
NAME_FINAL_IQ="$2"

## check H is a number and not negative
if ! [[ "$H" =~ ^[0-9]+$ ]] || ((H > 160)); then
  echo "error: H_size must be an integer 0..160 (got '$H')" >&2
  usage
fi

## check that file name is provided
if [[ -z "${NAME_FINAL_IQ//[[:space:]]/}" ]]; then
  die "NAME_FINAL_IQ must not be empty or whitespace"
fi

OUT_DIR="out"
RAW="${OUT_DIR}/tx_raw_H${H}.txt" ## Raw IQ!
VCD="${OUT_DIR}/tx_H${H}.vcd"     ## waveform file

PADDED="${OUT_DIR}/${NAME_FINAL_IQ}"

TB_SRC="dot11_tx_tb_base.v"         ## testbed file source template
TB_GEN="${OUT_DIR}/.gen_tb_H${H}.v" ## testbed with hole size set
VVP="${OUT_DIR}/.gen_H${H}.vvp"     ## sim file

########################## File Checks #######################################
[[ -f "$TB_SRC" ]] || die "$TB_SRC not found"
[[ -f ../src/dot11_tx.v ]] || die "../src/dot11_tx.v not found"
[[ -f ../src/openofdm_tx_pre_def.v ]] || die "../src/openofdm_tx_pre_def.v missing (normally generated by boards/ip_repo_gen.tcl; 'echo \"\" >' it to stub)"
## check meme file with frame data
[[ -f ../unit_test/test_vec/tx_intf.mem ]] || die "../unit_test/test_vec/tx_intf.mem not found"
## check IFFT twiddles
for m in 8 16 32 64; do
  [[ -e "icmem_${m}.mem" ]] || die "icmem_${m}.mem missing here (symlink ../src/icmem_${m}.mem)"
done
command -v iverilog >/dev/null || die "iverilog not installed (see README Requirements)"
command -v vvp >/dev/null || die "vvp not installed (see README Requirements)"

mkdir -p "$OUT_DIR" "$(dirname "$PADDED")"

# create testbench with args (i.e., H and out file name)
sed -e "s|num_stf_minus = 0;|num_stf_minus = ${H};|" \
  -e "s|\"dot11_tx_base\.txt\"|\"${RAW}\"|" \
  -e "s|\"dot11_tx_base\.vcd\"|\"${VCD}\"|" \
  "$TB_SRC" >"$TB_GEN"

grep -q "num_stf_minus = ${H};" "$TB_GEN" ||
  die "failed to patch num_stf_minus in $TB_SRC (did line 42 change?)"

cleanup() { rm -f "$TB_GEN" "$VVP"; }
trap cleanup EXIT

########################### Running Sim ########################
echo "==> compiling (H=${H})"
iverilog -g2012 -I ../src -o "$VVP" \
  $(ls ../src/*.v | grep -v 'dot11_tx_tb\.v') "$TB_GEN" \
  -s dot11_tx_tb_base 2>&1 |
  grep -vE 'axi_fifo_bram\.v|Pruning \(signed\)' || true

# the grep filter above would mask a compile failure, so check the artifact
[[ -s "$VVP" ]] || die "compile failed (see messages above)"

echo "==> running"
vvp "$VVP" >"${OUT_DIR}/vvp_H${H}.log" 2>&1

[[ -s "$RAW" ]] || die "simulation produced no samples; see ${OUT_DIR}/vvp_H${H}.log"
N_RAW=$(wc -l <"$RAW")
echo "    $RAW  ($N_RAW samples)"

########################### Padding ###########################################

## zero padding
pad() {
  local n="$1" i
  for ((i = 0; i < n; i++)); do printf '0 0\n'; done
}

{
  printf '0 0 0 0 0 0 0 %d 1\n' "$FC_MHZ"
  pad "$PRE"
  cat "$RAW"
  pad "$POST"
} >"$PADDED"

echo "    $PADDED  ($(wc -l <"$PADDED") lines = 1 hdr + $PRE pre + $N_RAW samples + $POST post)"

######################### Report ##################
if ((H > 0)); then
  START=$((160 - H)) # first sample index inside the hole
  echo "==> hole: samples ${START}..159 (H=${H})"
  awk -v s="$START" 'NR>s && NR<=160 { print ($1==0 && $2==0) ? "0" : "1" }' "$RAW" |
    tr -d '\n' | fold -w 8 | sed 's/^/    /'
  echo
  echo "    ^ per-sample on/off inside the hole (1=sample present, 0=zeroed)"
fi
